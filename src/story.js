// 勝利台詞：打贏宿敵用專屬台詞，否則依對手輪流挑一句（同一組對戰固定同一句）
export function winQuote(winner, loser) {
  const s = STORY[winner] || BOSS_STORY[winner];
  if (!s) return '';
  if (s.rival === loser && s.winRival) return s.winRival;
  const i = (winner.length * 7 + loser.charCodeAt(0) + loser.length) % s.win.length;
  return s.win[i];
}

